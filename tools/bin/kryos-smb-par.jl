#!/usr/bin/env julia
# The smb_simple variant of the science case (G6, phase 4 WP7c): par/kryos_NH-ANT_vilma2.nml with the surface of both domains from smb_simple.
#   julia tools/bin/kryos-smb-par.jl par/kryos_NH-ANT_vilma2.nml par/gate/g6-smb.nml
# [surface_nor], [surface_ant]: backend = "smb_simple", the keys surface_chion, chion, orbit removed (the group is validated against
# [surface_smb_simple] of input/kryos_defaults.nml: they are unknown keys), smb_simple = "smb_simple" (the module defaults of [smb_simple]).
# The `-p` list of the conversion note (backend only) stops at nml_validate for this reason.
function main(args)
    L = readlines(args[1]); out = String[]; ing = ""
    for l in L
        m = match(r"^&(\w+)", l)
        m !== nothing && (ing = String(m.captures[1]))
        strip(l) == "/" && (ing = "")
        if ing in ("surface_nor", "surface_ant")
            occursin(r"^\s*(surface_chion|chion|orbit)\s*=", l) && continue
            if occursin(r"^\s*backend\s*=", l)
                l = replace(l, "\"chion\"" => "\"smb_simple\"")
                push!(out, l); push!(out, "    smb_simple    = \"smb_simple\"   ! the module defaults of [smb_simple]: not tuned (G6)")
                continue
            end
        end
        push!(out, l)
    end
    open(args[2], "w") do io
        println(io, "! G6: the smb_simple variant of par/kryos_NH-ANT_vilma2.nml, generated by tools/bin/kryos-smb-par.jl (surface of both domains from smb_simple).")
        foreach(l -> println(io, l), out)
    end
end
main(ARGS)
