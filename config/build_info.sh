#!/bin/sh
# Writes the Fortran module kryos_build_info (core-design 7, 11): the git
# version of kryos and of the libraries it links, for the restart manifest.
#
#     sh config/build_info.sh <file.f90> <kryos dir> [<name>:<dir> ...]
#
# A version is `git describe --always --dirty` (the short hash, `-dirty` with
# uncommitted changes to tracked files), `unknown` outside a git checkout.
# The file is replaced only when its content changes, so an unchanged tree
# recompiles nothing.

out=$1
root=$2
shift 2

version() {
    v=$(git -C "$1" describe --always --dirty --abbrev=12 2>/dev/null) || v=unknown
    [ -n "$v" ] || v=unknown
    echo "$v"
}

names=""
gits=""
n=0
for pair in "$@"; do
    name=${pair%%:*}
    dir=${pair#*:}
    names="$names, \"$name\""
    gits="$gits, \"$(version "$dir")\""
    n=$((n + 1))
done
names=${names#, }
gits=${gits#, }

tmp="$out.tmp"
{
    echo "module kryos_build_info"
    echo "    ! Generated by config/build_info.sh at build time: do not edit."
    echo "    implicit none"
    echo "    character(len=*), parameter :: GIT_KRYOS = \"$(version "$root")\""
    echo "    character(len=32), parameter :: LIB_NAME($n) = [character(len=32) :: $names]"
    echo "    character(len=64), parameter :: LIB_GIT($n)  = [character(len=64) :: $gits]"
    echo "end module kryos_build_info"
} > "$tmp"

if cmp -s "$tmp" "$out"; then
    rm -f "$tmp"
else
    mv "$tmp" "$out"
fi
